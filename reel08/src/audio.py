def sos(kind, fc, order=2):
    return signal.butter(order, fc, kind, fs=SR, output="sos")
def lp(x, fc, o=2): return signal.sosfilt(sos("low", fc, o), x)
def hp(x, fc, o=2): return signal.sosfilt(sos("high", fc, o), x)
def bp(x, lo, hi, o=2): return signal.sosfilt(sos("band", [lo, hi], o), x)
def mtof(m): return 440.0 * 2 ** ((m - 69) / 12)
def noise(n): return rng.standard_normal(n)

def stereo_add(buf, sig, t0, gain=1.0, pan=0.0):
    i0 = int(t0 * SR)
    if i0 >= N or i0 + len(sig) <= 0: return
    a = max(0, -i0); sig = sig[a:]; i0 = max(0, i0)
    n = min(len(sig), N - i0); sig = sig[:n]
    l = np.cos((pan + 1) * np.pi / 4); r = np.sin((pan + 1) * np.pi / 4)
    buf[0, i0:i0 + n] += sig * gain * l * 1.414
    buf[1, i0:i0 + n] += sig * gain * r * 1.414

# ------------------------------------------------------------------ sound building blocks
def saw(f, n, detune=0.0):
    t = np.arange(n) / SR
    ph = (f * (1 + detune) * t) % 1.0
    return 2 * ph - 1
def sq(f, n):
    return np.sign(np.sin(2 * np.pi * f * np.arange(n) / SR))
def exp_env(n, decay, attack=0.002):
    t = np.arange(n) / SR
    e = np.exp(-t / decay)
    a = int(attack * SR)
    if a > 0: e[:a] *= np.linspace(0, 1, a)
    return e
def kick(gain=1.0):
    n = int(.45 * SR); t = np.arange(n) / SR
    f = 46 + 120 * np.exp(-t * 32); ph = 2 * np.pi * np.cumsum(f) / SR
    body = np.sin(ph) * np.exp(-t * 7.5)
    click = hp(noise(n), 2500) * np.exp(-t * 180) * .25
    return (body + click) * gain
def snare(gain=1.0):
    n = int(.28 * SR); t = np.arange(n) / SR
    tone = np.sin(2 * np.pi * 190 * t) * np.exp(-t * 28) * .5
    nz = hp(noise(n), 1500) * np.exp(-t * 16)
    return (tone + nz * .8) * gain
def clap(gain=1.0):
    n = int(.3 * SR); t = np.arange(n) / SR
    e = sum(np.exp(-np.clip(t - d, 0, None) * 38) * (t >= d) for d in (0, .011, .022)) * .5 + np.exp(-t * 14) * .5
    return bp(noise(n), 900, 5200) * e * gain * 1.6
def hat(gain=1.0, open_=False):
    n = int((.22 if open_ else .06) * SR); t = np.arange(n) / SR
    return hp(noise(n), 7000) * np.exp(-t * (14 if open_ else 70)) * gain
def pluck(f, dur=.35, bright=3500, gain=1.0):
    n = int(dur * SR); t = np.arange(n) / SR
    s = (saw(f, n, 0) + saw(f, n, .006) + .5 * sq(f * 2, n) * .0) * .5
    s = lp(s, bright, 2) * np.exp(-t / (dur * .33))
    return s * gain
def bell(f, dur=1.4, gain=1.0):
    n = int(dur * SR); t = np.arange(n) / SR
    s = sum(a * np.sin(2 * np.pi * f * r * t) * np.exp(-t / (dur * d)) for r, a, d in ((1, 1, .45), (2.0, .38, .3), (2.76, .22, .2), (4.07, .12, .12), (5.4, .06, .08)))
    return s * gain * .5
def pad(freqs, dur, gain=1.0, cutoff=1500, attack=.5, release=.8):
    n = int(dur * SR); s = np.zeros(n)
    for f in freqs:
        for dt in (-.009, 0, .011):
            s += saw(f, n, dt) / 6
    s = lp(s, cutoff, 2)
    e = np.ones(n); a = int(attack * SR); r = int(release * SR)
    e[:a] = np.linspace(0, 1, a) ** 1.5; e[-r:] *= np.linspace(1, 0, r) ** 1.5
    return s * e * gain
def bass(f, dur, gain=1.0):
    n = int(dur * SR); t = np.arange(n) / SR
    s = lp(saw(f, n) * .6 + np.sin(2 * np.pi * f * t), 520, 2)
    e = np.minimum(1, t / .005) * np.minimum(1, (dur - t) / .03) * np.exp(-t / (dur * 1.6))
    return s * e * gain
def sweep(dur, f0, f1, shape="bell", gain=1.0, width=1500):
    n = int(dur * SR); t = np.arange(n) / SR
    f = f0 * (f1 / f0) ** (t / dur); ph = 2 * np.pi * np.cumsum(f) / SR
    nz = lp(noise(n), width, 2)
    s = nz * np.sin(ph) * 2.0
    p = t / dur
    e = np.sin(np.pi * p) ** 2 if shape == "bell" else (p ** 2.2 if shape == "rise" else (1 - p) ** 2)
    return s * e * gain
def boom(gain=1.0, dur=1.6):
    n = int(dur * SR); t = np.arange(n) / SR
    f = 34 + 60 * np.exp(-t * 6); ph = 2 * np.pi * np.cumsum(f) / SR
    return (np.sin(ph) * np.exp(-t * 2.3) + lp(noise(n), 300) * np.exp(-t * 9) * .6) * gain
def crash(dur=1.8, gain=1.0):
    n = int(dur * SR); t = np.arange(n) / SR
    return hp(noise(n), 4200) * np.exp(-t * 2.4) * gain * .6
def pop(f=700, gain=1.0):
    n = int(.14 * SR); t = np.arange(n) / SR
    fr = f * (1 + .9 * np.exp(-t * 40)); ph = 2 * np.pi * np.cumsum(fr) / SR
    return np.sin(ph) * np.exp(-t * 32) * gain
def tick(gain=1.0, f=2600):
    n = int(.035 * SR); t = np.arange(n) / SR
    return (hp(noise(n), 1800) * .6 + np.sin(2 * np.pi * f * t)) * np.exp(-t * 120) * gain
def key(gain=1.0):
    n = int(.03 * SR); t = np.arange(n) / SR
    return (bp(noise(n), 2500, 7000) * np.exp(-t * 170) + np.sin(2 * np.pi * 180 * t) * np.exp(-t * 90) * .5) * gain
def ping(f=1318.5, gain=1.0):
    n = int(.45 * SR); t = np.arange(n) / SR
    s = np.sin(2 * np.pi * f * t) * np.exp(-t * 11) + .4 * np.sin(2 * np.pi * f * 1.5 * t) * np.exp(-t * 18)
    return s * gain * np.minimum(1, t / .002)
def shimmer(dur=1.2, gain=1.0):
    n = int(dur * SR); s = np.zeros(n); t = np.arange(n) / SR
    for _ in range(26):
        f = mtof(rng.choice([84, 88, 91, 93, 96, 100])); st = rng.uniform(0, dur * .8)
        i = int(st * SR); m = n - i; tt = np.arange(m) / SR
        s[i:] += np.sin(2 * np.pi * f * tt) * np.exp(-tt * rng.uniform(5, 10)) * rng.uniform(.3, 1)
    return s * gain * .22
def reverse(x): return x[::-1].copy()
def sumsig(*xs):
    n = max(len(x) for x in xs); o = np.zeros(n)
    for x in xs: o[:len(x)] += x
    return o

