def sidechain(depth, rel=.16):
    env = np.ones(N)
    for t in kick_times:
        i = int(t * SR); m = min(int(.6 * SR), N - i)
        if m <= 0: continue
        tt = np.arange(m) / SR; env[i:i + m] = np.minimum(env[i:i + m], 1 - depth * np.exp(-tt / rel))
    return env
sc = sidechain(.55)
def reverb(x, rt=1.4, wet=1.0):
    n = int(rt * SR); t = np.arange(n) / SR
    out = np.zeros_like(x)
    for ch in range(2):
        ir = lp(noise(n), 5500) * np.exp(-t * (6.9 / rt)); ir[:int(.012 * SR)] *= np.linspace(0, 1, int(.012 * SR)); ir /= np.sqrt((ir ** 2).sum())
        out[ch] = signal.fftconvolve(x[ch], ir)[:N] * wet
    return out
def delay(x, time=.375, fb=.38, n=4, mix=.5):
    out = x.copy(); d = int(time * SR)
    for k in range(1, n + 1):
        sh = np.zeros_like(x); sh[:, k * d:] = x[:, :N - k * d] * (fb ** k); 
        out += sh * mix
    return out
mus_wet = delay(MUS_WET, mix=.55)
