def load_vo(name, start, gain=1.0):
    a, sr = sf.read(f"{vo_dir}/{name}_{voice}.wav")
    if a.ndim > 1: a = a.mean(1)
    if sr != SR: a = signal.resample_poly(a, SR, sr)
    # trim leading/trailing silence
    thr = 0.012 * np.abs(a).max(); idx = np.where(np.abs(a) > thr)[0]
    a = a[max(0, idx[0] - int(.03 * SR)): idx[-1] + int(.12 * SR)]
    a = a * np.minimum(1, np.arange(len(a)) / (.008 * SR)) * np.minimum(1, (len(a) - np.arange(len(a))) / (.06 * SR))
    return a, start
